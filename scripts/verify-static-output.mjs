import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const distDir = resolve(process.cwd(), 'dist');

const requiredFiles = [
  'index.html',
  'logos/logo-1024.png',
  'logos/logo-48.png',
  'rss.xml',
  'robots.txt',
  'sitemap.xml',
  'page/1/index.html',
  'pages/about/index.html',
  'tags/index.html',
  'categories/index.html',
  'posts/bold-mage/index.html',
];

for (const relativePath of requiredFiles) {
  const absolutePath = resolve(distDir, relativePath);

  if (!existsSync(absolutePath)) {
    throw new Error(`Missing expected build artifact: ${relativePath}`);
  }
}

const home = readFileSync(resolve(distDir, 'index.html'), 'utf8');
const pageOne = readFileSync(resolve(distDir, 'page', '1', 'index.html'), 'utf8');
const about = readFileSync(resolve(distDir, 'pages', 'about', 'index.html'), 'utf8');
const bigSample = readFileSync(resolve(distDir, 'posts', 'big-sample-test', 'index.html'), 'utf8');
const rss = readFileSync(resolve(distDir, 'rss.xml'), 'utf8');
const sitemap = readFileSync(resolve(distDir, 'sitemap.xml'), 'utf8');
const robots = readFileSync(resolve(distDir, 'robots.txt'), 'utf8');

const assertions = [
  ['Home page includes the favicon asset path', home.includes('/logos/logo-48.png')],
  ['Home page does not reference a missing rowland.jpeg asset', !home.includes('/rowland.jpeg')],
  ['Page 1 archive includes pagination navigation', pageOne.includes('aria-label="Pagination"')],
  ['About page is published under /pages/about/', about.includes('This phase-1 migration keeps the existing site structure intact')],
  [
    'Big sample post includes a heading self-link generated by rehype-autolink-headings',
    bigSample.includes('href="#headers"') && bigSample.includes('aria-hidden="true"')
  ],
  ['Big sample post exposes article Open Graph metadata', bigSample.includes('<meta property="og:type" content="article">')],
  ['Big sample post exposes BlogPosting JSON-LD', bigSample.includes('"@type":"BlogPosting"')],
  ['Big sample post preserves raw HTML definition lists', bigSample.includes('<dl>')],
  ['Big sample post preserves remote markdown images', bigSample.includes('raw/master/src/common/images/icon48.png')],
  ['Big sample post includes the Disqus thread container', bigSample.includes('id="disqus_thread"')],
  ['Big sample post preserves the canonical Disqus page URL', bigSample.includes('this.page.url = "https://rowlandekemezie.com/posts/big-sample-test/";')],
  ['Big sample post preserves the title-based Disqus identifier', bigSample.includes('this.page.identifier = "Big-Sample_Test";')],
  ['RSS contains the site feed title', rss.includes('<title>Rowland I. Ekemezie</title>')],
  ['RSS contains a canonical post URL', rss.includes('https://rowlandekemezie.com/posts/bold-mage/')],
  ['Sitemap contains the site root URL', sitemap.includes('<loc>https://rowlandekemezie.com/</loc>')],
  ['Sitemap contains the about page URL', sitemap.includes('<loc>https://rowlandekemezie.com/pages/about/</loc>')],
  ['Sitemap contains a taxonomy URL', sitemap.includes('<loc>https://rowlandekemezie.com/tags/programming/</loc>')],
  ['Robots references the canonical sitemap URL', robots.includes('Sitemap: https://rowlandekemezie.com/sitemap.xml')],
];

for (const [description, passed] of assertions) {
  if (!passed) {
    throw new Error(`Static output verification failed: ${description}`);
  }
}

console.log('Static output verification passed.');
